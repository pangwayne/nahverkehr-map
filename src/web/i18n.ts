export type Texts = typeof de;

let current: Lang = pageLang();
const listeners: (() => void)[] = [];

// The texts in the current language.
export function t(): Texts {
  return current === "de" ? de : en;
}

export function getLang(): Lang {
  return current;
}

// Switch language in place and let every open view redraw. The app itself changes language by loading the other
// address (main.ts).
export function setLang(lang: Lang, remember = true): void {
  current = lang;
  if (remember) rememberLang(lang);
  for (const fn of listeners) fn();
}

// Keep the language someone picked.
export function rememberLang(lang: Lang): void {
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    // Storage blocked (private mode, say): the switch still works, for this page only.
  }
}

export function onLangChange(fn: () => void): void {
  listeners.push(fn);
}

// The language of this address: /de/... is German, anything else English.
export function pageLang(): Lang {
  return /^\/de(\/|$)/.test(globalThis.location?.pathname ?? "") ? "de" : "en";
}

// The language picked earlier in this browser, if any.
export function savedLang(): Lang | null {
  try {
    const v = globalThis.localStorage?.getItem(STORAGE_KEY);
    return v === "de" || v === "en" ? v : null;
  } catch {
    return null;
  }
}
